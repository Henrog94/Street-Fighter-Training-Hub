
import mongoose from "mongoose";

const trainingPlanSchema = new mongoose.Schema(
  {
    // The account that owns this training session.
    user: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
      index: true
    },

    // Fighter selected in the training planner.
    fighter: {
      type: String,
      required: true,
      trim: true
    },

    // Main focus of the training session.
    focus: {
      type: String,
      required: true,
      trim: true
    },

    // The goal the user wants to achieve.
    goal: {
      type: String,
      required: true,
      trim: true
    },

    // Recommendations generated by the planner.
    recommendations: {
      type: [String],
      default: []
    },

    // Optional notes written by the user.
    notes: {
      type: String,
      default: ""
    },

    // Calendar date in YYYY-MM-DD format.
    scheduledDate: {
      type: String,
      required: true,
      match: /^\d{4}-\d{2}-\d{2}$/
    },

    // Start time in 24-hour HH:mm format.
    startTime: {
      type: String,
      required: true,
      match: /^([01]\d|2[0-3]):[0-5]\d$/
    },

    // Length of the training session in minutes.
    duration: {
      type: Number,
      required: true,
      min: 15,
      max: 240,
      default: 60
    },

    // Status of the training session.
    status: {
      type: String,
      enum: ["scheduled", "completed", "cancelled"],
      default: "scheduled"
    }
  },
  {
    timestamps: true
  }
);

// Helps retrieve a user's sessions in calendar order.
trainingPlanSchema.index({
  user: 1,
  scheduledDate: 1,
  startTime: 1
});

const TrainingPlan = mongoose.model(
  "TrainingPlan",
  trainingPlanSchema
);

export default TrainingPlan;
